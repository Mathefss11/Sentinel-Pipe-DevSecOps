"""Derives SentinelPipe's Gitleaks ruleset from the upstream default configuration.

Usage (from the repository root):

    curl -sSfL -o gitleaks-default.toml \
      https://raw.githubusercontent.com/gitleaks/gitleaks/v8.30.1/config/gitleaks.toml
    python scripts/dev/derive-gitleaks-rules.py gitleaks-default.toml \
      services/sentinel-worker/src/sentinel_worker/scanners/gitleaks-rules.toml

The upstream file is copied unchanged except for path-based allowlists, which a
repository author controls by naming files (ADR-0010, security review of Slice 1). The
script:

* removes ``paths`` from the global ``[allowlist]``, keeping its value-based ``regexes``
  and ``stopwords``;
* removes every ``[[rules.allowlists]]`` block that contains ``paths``. This includes an
  ``AND`` block whose regexes would otherwise apply to every file.

It refuses input whose SHA-256 differs from the reviewed upstream file, and verifies the
result with ``tomllib``.
"""

from __future__ import annotations

import hashlib
import sys
import tomllib
from pathlib import Path

UPSTREAM_VERSION = "8.30.1"
UPSTREAM_SHA256 = "e163e53b9e7e8a8511e77271e2b323ed057759542a6d988258afe3a1fa329caf"
HEADER = f"""\
# SentinelPipe Gitleaks ruleset, derived from Gitleaks v{UPSTREAM_VERSION} config/gitleaks.toml
# (https://github.com/gitleaks/gitleaks, MIT License, Copyright (c) 2019 Zachary Rice).
# Upstream SHA-256: {{sha256}}
# Generated by scripts/dev/derive-gitleaks-rules.py. Do not edit by hand.
# Changes: path-based allowlists removed (global [allowlist].paths and every
# [[rules.allowlists]] block with paths), because repository authors control file names.
# Value-based allowlists (regexes, stopwords) are unchanged.

"""


def derive(text: str) -> str:
    lines = text.splitlines(keepends=True)
    output: list[str] = []
    index = 0
    section = ""
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        if stripped.startswith("["):
            section = stripped
            if stripped == "[[rules.allowlists]]":
                end = index + 1
                while end < len(lines) and not lines[end].lstrip().startswith("["):
                    end += 1
                # A header line starting with "[" inside a value never occurs in this file;
                # verified below by parsing the result.
                block = lines[index:end]
                if any(entry.strip().startswith("paths") for entry in block):
                    index = end
                    continue
                output.extend(block)
                index = end
                continue
        if section == "[allowlist]" and stripped.startswith("paths"):
            depth = line.count("[") - line.count("]")
            index += 1
            while depth > 0 and index < len(lines):
                depth += lines[index].count("[") - lines[index].count("]")
                index += 1
            continue
        output.append(line)
        index += 1
    return "".join(output)


def verify(original: dict, derived: dict) -> None:
    assert "paths" not in derived["allowlist"], "global path allowlist remains"
    assert derived["allowlist"]["regexes"] == original["allowlist"]["regexes"]
    assert derived["allowlist"]["stopwords"] == original["allowlist"]["stopwords"]
    assert [rule["id"] for rule in derived["rules"]] == [rule["id"] for rule in original["rules"]]
    for before, after in zip(original["rules"], derived["rules"], strict=True):
        kept = [block for block in before.get("allowlists", []) if "paths" not in block]
        assert after.get("allowlists", []) == kept, before["id"]
        assert {k: v for k, v in after.items() if k != "allowlists"} == {
            k: v for k, v in before.items() if k != "allowlists"
        }, before["id"]


def main(source: str, target: str) -> int:
    raw = Path(source).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != UPSTREAM_SHA256:
        print(f"refusing: upstream SHA-256 {digest} is not the reviewed file", file=sys.stderr)
        return 1
    text = raw.decode("utf-8")
    derived = derive(text)
    verify(tomllib.loads(text), tomllib.loads(derived))
    Path(target).write_text(HEADER.format(sha256=digest) + derived, encoding="utf-8", newline="\n")
    print(f"wrote {target} from upstream {digest}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    sys.exit(main(sys.argv[1], sys.argv[2]))
